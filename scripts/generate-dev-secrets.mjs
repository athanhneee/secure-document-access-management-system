import { randomBytes } from 'node:crypto';
import { chmod, mkdir, open } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const repositoryRoot = fileURLToPath(new URL('../', import.meta.url));
export const defaultOutput = path.join(repositoryRoot, '.local', 'dev.env');

function randomSecret(bytes = 32) {
  return randomBytes(bytes).toString('base64url');
}

export function buildDevelopmentEnvironment() {
  const postgresPassword = randomSecret();
  const redisPassword = randomSecret();
  const storageAccessKey = `sda${randomSecret(12)}`;
  const storageSecretKey = randomSecret(32);
  const grafanaPassword = randomSecret();

  return [
    '# Generated by scripts/generate-dev-secrets.mjs. Local development only.',
    '# This file is gitignored. Delete and regenerate it if disclosure is suspected.',
    'COMPOSE_PROJECT_NAME=secure-document-access-system-local',
    'NODE_ENV=development',
    'POSTGRES_USER=sda_local',
    `POSTGRES_PASSWORD=${postgresPassword}`,
    'POSTGRES_DB=secure_docs',
    `DATABASE_URL=postgresql://sda_local:${postgresPassword}@127.0.0.1:5432/secure_docs?schema=public`,
    `REDIS_PASSWORD=${redisPassword}`,
    `REDIS_URL=redis://:${redisPassword}@127.0.0.1:6379/0`,
    `MINIO_ROOT_USER=${storageAccessKey}`,
    `MINIO_ROOT_PASSWORD=${storageSecretKey}`,
    'STORAGE_ENDPOINT=127.0.0.1',
    'STORAGE_PORT=9000',
    `STORAGE_ACCESS_KEY=${storageAccessKey}`,
    `STORAGE_SECRET_KEY=${storageSecretKey}`,
    'STORAGE_BUCKET_DOCUMENTS=secure-documents',
    'STORAGE_BUCKET_DERIVATIVES=secure-derivatives',
    'STORAGE_BUCKET_QUARANTINE=secure-quarantine',
    'STORAGE_USE_SSL=false',
    'GRAFANA_ADMIN_USER=sda-local-admin',
    `GRAFANA_ADMIN_PASSWORD=${grafanaPassword}`,
    `APP_ENCRYPTION_MASTER_KEY=${randomBytes(32).toString('hex')}`,
    '',
  ].join('\n');
}

export async function generateDevelopmentSecrets({ output = defaultOutput, force = false } = {}) {
  await mkdir(path.dirname(output), { recursive: true });
  const handle = await open(output, force ? 'w' : 'wx', 0o600);
  try {
    await handle.writeFile(buildDevelopmentEnvironment(), { encoding: 'utf8' });
  } finally {
    await handle.close();
  }
  await chmod(output, 0o600).catch(() => undefined);
  return output;
}

async function main() {
  const force = process.argv.includes('--force');
  try {
    const output = await generateDevelopmentSecrets({ force });
    console.log(`Generated local development secrets at ${path.relative(repositoryRoot, output)}.`);
  } catch (error) {
    if (error?.code === 'EEXIST') {
      console.log('.local/dev.env already exists; leaving it unchanged. Use --force to rotate it.');
      return;
    }
    throw error;
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await main();
}
